    private static IReadOnlyList<SubtitleTrack> ReadCaptions(JsonElement root,string id)
    {
        var captions=Array(root,"captions");var transcripts=Array(root,"availableTranscripts");
        if(captions.Length>128||transcripts.Length>128)throw new InvalidDataException("Wistia returned too many caption languages.");
        var languages=new Dictionary<string,string>(StringComparer.Ordinal);var declared=new Dictionary<string,(string Language,bool Automatic,string? Url)>(StringComparer.Ordinal);
        foreach(var transcript in transcripts)
        {
            var code=Text(transcript,"wistiaLanguageCode")??Text(transcript,"language");if(code is null||!True(transcript,"hasCaptions"))continue;
            ValidateLanguage(code);var language=Text(transcript,"bcp47LanguageTag")??Text(transcript,"iso639_2_language_code")??code;ValidateLanguage(language);
            if(!languages.TryAdd(code,language))throw new InvalidDataException("Wistia repeated a transcript language.");
        }
        foreach(var caption in captions)
        {
            var code=Text(caption,"language")??throw new InvalidDataException("Wistia omitted a caption language.");ValidateLanguage(code);
            var language=Text(caption,"bcp47LanguageTag")??languages.GetValueOrDefault(code)??(code switch{"eng"=>"en","spa"=>"es","fra"=>"fr","deu"=>"de","ita"=>"it","jpn"=>"ja","zho"=>"zh","por"=>"pt","rus"=>"ru",_=>code});ValidateLanguage(language);
            if(!declared.TryAdd(code,(language,True(caption,"automatic")||True(caption,"isAutoGenerated"),Text(caption,"url"))))throw new InvalidDataException("Wistia repeated a caption language.");
        }
        foreach(var pair in languages)declared.TryAdd(pair.Key,(pair.Value,false,null));
        var result=new List<SubtitleTrack>();var trackIds=new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach(var pair in declared)
        {
            var formats=pair.Value.Url is null?new[]{"vtt","srt"}:new[]{Path.GetExtension(Resource(pair.Value.Url).AbsolutePath).TrimStart('.').ToLowerInvariant()};
            foreach(var format in formats)
            {
                if(format is not ("vtt" or "srt")||!trackIds.Add(pair.Value.Language+":"+format+":"+pair.Value.Automatic))throw new InvalidDataException("Wistia caption formats or language aliases are ambiguous.");
                var url=pair.Value.Url is { } provided?Resource(provided):new Uri("https://fast.wistia.com/embed/captions/"+id+"."+format+"?language="+Uri.EscapeDataString(pair.Key));
                if(url.Scheme!="https"||!url.IsDefaultPort||url.UserInfo.Length>0||url.Fragment.Length>0)throw new InvalidDataException("Wistia caption resources require secure declared URLs.");
                if(url.Host=="api.wistia.com"&&!ApiCaption(url,id,pair.Key,format))throw new InvalidDataException("Wistia caption API changed its media or language identity.");
                result.Add(new(){Url=url,Language=pair.Value.Language,Extension=format,Automatic=pair.Value.Automatic,ResourceIdentity="wistia:"+id+":"+pair.Key+":"+format,ResourceExpires=PlaybackResourceExpiry.Read(url)});
            }
        }
        return result;
    }
    private static void ValidateLanguage(string value){if(!Regex.IsMatch(value,@"\A[A-Za-z0-9][A-Za-z0-9_-]{0,31}\z",RegexOptions.CultureInvariant,TimeSpan.FromMilliseconds(100)))throw new InvalidDataException("Wistia declared an invalid caption language.");}
    private static bool ApiCaption(Uri url,string id,string code,string format)=>url.Host=="api.wistia.com"&&url.AbsolutePath=="/modern/medias/"+id+"/captions/"+code+"."+format&&url.Query.Length==0;
    private static async Task<PageMetadata> ResolveApiCaptionsAsync(PageMetadata page,string id,NativeDownloadRequest request,NativeHostingCredentials? credentials,MediaHttp controlled,CancellationToken ct)
    {
        var selected=SubtitleSelection.Select(page.Subtitles,request);var replacements=new Dictionary<SubtitleTrack,SubtitleTrack>(ReferenceEqualityComparer.Instance);long total=0;
        foreach(var track in selected.Where(t=>t.Url.Host=="api.wistia.com"))
        {
            if(credentials is null)throw new NotSupportedException("This caption resource requires its exact supplied Wistia media credential.");
            var document=await controlled.GetDocumentAsync(track.Url,2*1024*1024,ct,new Dictionary<string,string>{["Authorization"]="Bearer "+credentials.AccessToken}).ConfigureAwait(false);
            if(document.Url!=track.Url||(total+=Encoding.UTF8.GetByteCount(document.Text))>32*1024*1024)throw new InvalidDataException("Wistia changed or exceeded its caption API resources.");
            var text=document.Text.TrimStart('\uFEFF',' ','\r','\n');
            if(track.Extension=="vtt"&&!text.StartsWith("WEBVTT",StringComparison.Ordinal)||!text.Contains("-->",StringComparison.Ordinal)||text.StartsWith("<",StringComparison.Ordinal))throw new InvalidDataException("Wistia did not return timed captions.");
            replacements[track]=new(){Url=track.Url,Language=track.Language,Extension=track.Extension,Automatic=track.Automatic,ResourceIdentity=track.ResourceIdentity,ResourceExpires=track.ResourceExpires,Content=document.Text};
        }
        return page with {Subtitles=page.Subtitles.Select(t=>replacements.GetValueOrDefault(t)??t).ToArray()};
    }
